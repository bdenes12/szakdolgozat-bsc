#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
CREATE EXTENSION IF NOT EXISTS anon;

ALTER DATABASE ${POSTGRES_DB} SET anon.transparent_dynamic_masking TO true;
ALTER DATABASE ${POSTGRES_DB} SET anon.masking_policies TO 'support';

SELECT anon.init();

CREATE ROLE ${STAGING_SUPPORT_USER} LOGIN PASSWORD '${STAGING_SUPPORT_PASSWORD}';
CREATE ROLE ${STAGING_ANALYST_USER} LOGIN PASSWORD '${STAGING_ANALYST_PASSWORD}';

GRANT USAGE ON SCHEMA public TO ${STAGING_SUPPORT_USER};
GRANT SELECT ON ALL TABLES IN SCHEMA public TO ${STAGING_SUPPORT_USER};

GRANT USAGE ON SCHEMA anon TO ${STAGING_SUPPORT_USER};
GRANT SELECT ON ALL TABLES IN SCHEMA anon TO ${STAGING_SUPPORT_USER};
GRANT SELECT ON ALL SEQUENCES IN SCHEMA anon TO ${STAGING_SUPPORT_USER};

SECURITY LABEL FOR support ON ROLE ${STAGING_SUPPORT_USER} IS 'MASKED';

CREATE SCHEMA dev_export;
CREATE SCHEMA analytics;

GRANT USAGE ON SCHEMA analytics TO ${STAGING_ANALYST_USER};
ALTER DEFAULT PRIVILEGES IN SCHEMA analytics GRANT SELECT ON TABLES TO ${STAGING_ANALYST_USER};
EOSQL